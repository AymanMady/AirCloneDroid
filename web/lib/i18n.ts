const DICTS: Record<Lang, Dict> = { fr, en };

export function translate(lang: Lang, key: string, vars?: Record<string, string>): string {
  let s = DICTS[lang]?.[key] ?? fr[key] ?? key;
  if (vars) {
    for (const k of Object.keys(vars)) s = s.replace(`{${k}}`, vars[k]);
  }
  return s;
}
